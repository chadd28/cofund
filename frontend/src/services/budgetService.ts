  /**
   * Log transaction statistics for debugging
   */
  private static logTransactionStatistics(transactions: Transaction[]) {
    const expenses = transactions.filter(tx => tx.type === 'expense');
    const income = transactions.filter(tx => tx.type === 'income');
    const totalExpenses = expenses.reduce((sum, tx) => sum + Math.abs(tx.amount), 0);
    const totalIncome = income.reduce((sum, tx) => sum + tx.amount, 0);
    
    const categoryStats = new Map<string, { count: number; total: number; amounts: number[] }>();
    
    expenses.forEach(tx => {
      const category = tx.user_category || tx.teller_category || 'Uncategorized';
      const amount = Math.abs(tx.amount);
      
      if (!categoryStats.has(category)) {
        categoryStats.set(category, { count: 0, total: 0, amounts: [] });
      }
      
      const stats = categoryStats.get(category)!;
      stats.count++;
      stats.total += amount;
      stats.amounts.push(amount);
    });
    
    console.log('=== Transaction Statistics ===');
    console.log(`Total Income: $${totalIncome.toFixed(2)}`);
    console.log(`Total Expenses: $${totalExpenses.toFixed(2)}`);
    console.log(`Income Transactions: ${income.length}`);
    console.log(`Expense Transactions: ${expenses.length}`);
    console.log(`\nCategory Breakdown:`);
    
    let runningTotal = 0;
    Array.from(categoryStats.entries())
      .sort((a, b) => b[1].total - a[1].total)
      .forEach(([category, stats]) => {
        const percentage = (stats.total / totalExpenses * 100).toFixed(1);
        const average = (stats.total / stats.count).toFixed(2);
        runningTotal += stats.total;
        console.log(`${category}:`);
        console.log(`  - Count: ${stats.count} transactions`);
        console.log(`  - Total: $${stats.total.toFixed(2)} (${percentage}%)`);
        console.log(`  - Average: $${average}`);
        console.log(`  - Running Total: $${runningTotal.toFixed(2)}`);
      });
    
    console.log(`\nVerification: Sum of all categories = $${runningTotal.toFixed(2)}`);
    console.log(`Should equal Total Expenses = $${totalExpenses.toFixed(2)}`);
  }
